from typing import Protocol

from api.contracts import CitizenQueryPageInput, TicketFilters, TicketInsertInput, TicketUpdateInput
from api.models import OpenTicketMatch, Ticket


class TicketRepositoryInterface(Protocol):
    def get_by_id(self, ticket_id: int) -> Ticket | None: ...
    def get_by_code(self, code: str) -> Ticket | None: ...
    def get_by_code_for_update(self, code: str) -> Ticket | None: ...
    def list_by_filters(self, filters: TicketFilters | None = None) -> list[Ticket]: ...
    def create(self, data: TicketInsertInput) -> Ticket: ...
    def create_if_code_available(self, data: TicketInsertInput) -> Ticket | None: ...
    def list_open_matches(
        self,
        *,
        address_id: int,
        failure_type_id: int,
        status_names: tuple[str, ...],
        limit: int,
        lock: bool = False,
    ) -> list[OpenTicketMatch]: ...
    def update(self, data: TicketUpdateInput) -> Ticket | None: ...
    def list_citizen_reports(self, reported_by: int, page: CitizenQueryPageInput, cursor_position=None) -> list[dict]: ...
    def get_citizen_report(self, reported_by: int, code: str) -> dict | None: ...
    def get_citizen_report_id(self, reported_by: int, code: str) -> int | None: ...
    def get_public_report(self, code: str) -> dict | None: ...

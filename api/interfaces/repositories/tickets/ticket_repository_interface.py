from typing import Protocol

from api.contracts import TicketFilters, TicketInsertInput, TicketUpdateInput
from api.models import OpenTicketMatch, Ticket


class TicketRepositoryInterface(Protocol):
    def get_by_id(self, ticket_id: int) -> Ticket | None: ...
    def get_by_code(self, code: str) -> Ticket | None: ...
    def list_by_filters(self, filters: TicketFilters | None = None) -> list[Ticket]: ...
    def create(self, data: TicketInsertInput) -> Ticket: ...
    def create_if_code_available(self, data: TicketInsertInput) -> Ticket | None: ...
    def list_open_matches(
        self,
        *,
        address_id: int,
        failure_type_id: int,
        status_names: tuple[str, ...],
        limit: int,
        lock: bool = False,
    ) -> list[OpenTicketMatch]: ...
    def update(self, data: TicketUpdateInput) -> Ticket | None: ...

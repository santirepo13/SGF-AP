from typing import Protocol

from api.contracts import (
    CitizenRegistrationInput,
    ExecutionContext,
    OperationResult,
    UserActivationInput,
    UserCreateInput,
    UserFilters,
    UserLoginInput,
    UserLoginOutput,
    PasswordRecoveryRequestInput,
    PasswordRecoveryRequestOutput,
    PasswordRecoveryVerifyInput,
    PasswordRecoveryVerifyOutput,
    PasswordResetInput,
    PasswordResetOutput,
    UserOutput,
    UserUpdateInput,
)


class UserServiceInterface(Protocol):
    def get_by_id(self, context: ExecutionContext, user_id: int) -> OperationResult[UserOutput]: ...
    def get_by_email(self, context: ExecutionContext, email: str) -> OperationResult[UserOutput]: ...
    def list_by_filters(self, context: ExecutionContext, filters: UserFilters | None = None) -> OperationResult[list[UserOutput]]: ...
    def register_citizen(
        self,
        context: ExecutionContext,
        data: CitizenRegistrationInput,
    ) -> OperationResult[UserOutput]: ...
    def login(self, context: ExecutionContext, data: UserLoginInput) -> OperationResult[UserLoginOutput]: ...
    def request_password_recovery(self, context: ExecutionContext, data: PasswordRecoveryRequestInput) -> OperationResult[PasswordRecoveryRequestOutput]: ...
    def verify_password_recovery(self, context: ExecutionContext, data: PasswordRecoveryVerifyInput) -> OperationResult[PasswordRecoveryVerifyOutput]: ...
    def complete_password_recovery(self, context: ExecutionContext, data: PasswordResetInput) -> OperationResult[PasswordResetOutput]: ...
    def get_current_user(self, context: ExecutionContext) -> OperationResult[UserOutput]: ...
    def create(self, context: ExecutionContext, data: UserCreateInput) -> OperationResult[UserOutput]: ...
    def update(self, context: ExecutionContext, data: UserUpdateInput) -> OperationResult[UserOutput]: ...
    def set_active(self, context: ExecutionContext, data: UserActivationInput) -> OperationResult[UserOutput]: ...
